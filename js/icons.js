var IC={};
function toHsv(h){var r=parseInt(h.slice(1,3),16)/255,g=parseInt(h.slice(3,5),16)/255,b=parseInt(h.slice(5,7),16)/255,mx=Math.max(r,g,b),mn=Math.min(r,g,b),d=mx-mn,k=0;if(d){if(mx===r)k=((g-b)/d+(g<b?6:0))/6;else if(mx===g)k=((b-r)/d+2)/6;else k=((r-g)/d+4)/6}return[k*360,mx?d/mx*100:0,mx*100]}
function fromHsv(h,s,v){s/=100;v/=100;var f=function(n){var k=(n+h/60)%6;return Math.round(255*(v-v*s*Math.max(0,Math.min(k,4-k,1)))).toString(16).padStart(2,"0")};return"#"+f(5)+f(3)+f(1)}
function iconFor(id,color){
  if(IC[id])return IC[id];
  var K=3,cv=document.createElement("canvas");cv.width=cv.height=32*K;var x=cv.getContext("2d");
  var a=toHsv(/^#[0-9a-f]{6}$/i.test(color||"")?color:"#888888"),h=a[0],s=a[1],v=Math.max(a[2],72);
  var accent=fromHsv(h,Math.min(82,Math.max(28,s)),Math.max(66,v));
  var P={w:"#e9e8e2",c:accent,l:fromHsv(h,Math.min(48,s),Math.min(96,v+18)),d:fromHsv(h,Math.min(80,s),Math.max(24,v*.48)),g:"#d8c58c",r:"#bd716b"};
  function R(X,Y,W,H,c){x.fillStyle=c;x.fillRect(X*K,Y*K,W*K,H*K)}
  /* A consistent dark broadcast tile; channel identity lives in the inset and glyph. */
  R(1,1,30,30,"#08090a");R(2,0,28,1,"#56565a");R(0,2,1,28,"#56565a");
  R(2,2,28,28,"#191a1c");R(3,3,26,2,accent);R(3,27,26,2,"#090a0b");
  (GLYPHS[id]||GLYPHS.tv).forEach(function(row,y){for(var i=0;i<row.length;i++){var ch=row[i];if(ch!=="."&&P[ch])R(4+i*2,4+y*2,2,2,P[ch])}});
  return IC[id]=cv.toDataURL()}
function logoFor(c){
  if(c && c.id && /^[a-z0-9-]+$/.test(c.id))return "assets/channel-icons/"+c.id+".png?v=5";
  return iconFor(c.id,c.color);
}
