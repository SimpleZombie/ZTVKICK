def noise(a,amt,rng,y0=0,y1=H,mono=True):
    n=rng.random((y1-y0,W,1)).astype(np.float32)*255
    a[y0:y1]=a[y0:y1]*(1-amt)+n*amt
_scan=None
def crt(a):
    """upscale x4 with hard pixels, darken every 4th row (scanlines), soft vignette. returns uint8 1280x720"""
    global _scan
    big=np.repeat(np.repeat(np.clip(a,0,255),S,0),S,1)
    if _scan is None:
        yy,xx=np.mgrid[0:H*S,0:W*S].astype(np.float32);cx,cy=W*S/2,H*S/2
        v=1-0.38*(((xx-cx)/cx)**2+((yy-cy)/cy)**2)**1.4
        sl=np.where((np.arange(H*S)%S)==S-1,.72,1.0).astype(np.float32)[:,None]
        _scan=(np.clip(v,0,1)*sl)[...,None]
    return np.clip(big*_scan,0,255).astype(np.uint8)
