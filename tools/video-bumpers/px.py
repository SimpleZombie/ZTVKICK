def canvas(c=(0,0,0)):a=np.zeros((H,W,3),np.float32);a[:]=c;return a
def hexc(h):h=h.lstrip("#");return tuple(int(h[i:i+2],16) for i in (0,2,4))
def rect(a,x,y,w,h,c,alpha=1.0):
    x0,y0,x1,y1=max(0,int(x)),max(0,int(y)),min(W,int(x+w)),min(H,int(y+h))
    if x1>x0 and y1>y0:a[y0:y1,x0:x1]=a[y0:y1,x0:x1]*(1-alpha)+np.array(c,np.float32)*alpha
def vgrad(a,y0,y1,c0,c1):
    for y in range(max(0,y0),min(H,y1)):
        t=(y-y0)/max(1,y1-y0-1);a[y,:]=[c0[i]+(c1[i]-c0[i])*t for i in range(3)]
def text_w(s,sc=1,gap=1):return len(s)*(5+gap)*sc-gap*sc
def text(a,s,x,y,c,sc=1,gap=1,alpha=1.0,shadow=None):
    if x=="c":x=(W-text_w(s,sc,gap))//2
    if shadow:text(a,s,x+sc,y+sc,shadow,sc,gap,alpha)
    for i,ch in enumerate(s.upper()):
        g=F.get(ch,F["?"])
        for r,row in enumerate(g):
            for k,b in enumerate(row):
                if b=="1":rect(a,x+i*(5+gap)*sc+k*sc,y+r*sc,sc,sc,c,alpha)
